/**
 * Which files in public/ are actually referenced, and which are not.
 *
 * The photo library was mirrored wholesale from the property's own sites, so
 * public/media holds considerably more than the site renders. Committing all of
 * it would put tens of megabytes of unreferenced JPEGs in a public repository
 * and in every clone, for no benefit.
 *
 * Referencing is resolved three ways, because the site names images three ways:
 *   1. a literal "/media/xxx.webp" anywhere in src/ or sanity/
 *   2. a key in src/content/generated/*.ts (the suite and experience maps),
 *      which components index into rather than writing the path out
 *   3. an entry in the gallery manifest
 *
 * Writes MEDIA-MANIFEST.md — the record of what was excluded and why — and
 * prints the .gitignore lines needed to exclude the rest.
 *
 *   node scripts/media-manifest.mjs
 */
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";

const PUBLIC = "public";
const CODE_ROOTS = ["src", "sanity", "scripts"];

/* ── every file under public/ ──────────────────────────────────────────── */
const all = [];
(function walk(dir) {
  for (const e of readdirSync(dir)) {
    const p = join(dir, e);
    const st = statSync(p);
    if (st.isDirectory()) walk(p);
    else all.push({ path: p.split(sep).join("/"), bytes: st.size });
  }
})(PUBLIC);

/* ── every string that could name one ──────────────────────────────────── */
let corpus = "";
(function walk(dir) {
  for (const e of readdirSync(dir)) {
    const p = join(dir, e);
    const st = statSync(p);
    if (st.isDirectory()) return walk(p);
    if (!/\.(ts|tsx|js|jsx|mjs|cjs|json|md|css)$/.test(e)) continue;
    corpus += readFileSync(p, "utf8") + "\n";
  }
});
for (const root of CODE_ROOTS) {
  (function walk(dir) {
    for (const e of readdirSync(dir)) {
      const p = join(dir, e);
      let st;
      try { st = statSync(p); } catch { continue; }
      if (st.isDirectory()) { walk(p); continue; }
      if (!/\.(ts|tsx|js|jsx|mjs|cjs|json|md|css)$/.test(e)) continue;
      try { corpus += readFileSync(p, "utf8") + "\n"; } catch { /* binary */ }
    }
  })(root);
}

const referenced = new Set();
const unreferenced = [];
for (const f of all) {
  const web = "/" + relative(PUBLIC, f.path.split("/").join(sep)).split(sep).join("/");
  const basename = web.split("/").pop();
  /* Match the full web path or the bare filename — generated maps store the
     full path, but a few components interpolate the basename. */
  if (corpus.includes(web) || corpus.includes(basename)) referenced.add(f.path);
  else unreferenced.push(f);
}

const kb = (n) => `${(n / 1024).toFixed(0)} kB`;
const mb = (n) => `${(n / 1024 / 1024).toFixed(1)} MB`;
const sum = (xs) => xs.reduce((a, b) => a + b.bytes, 0);

const keptBytes = sum(all.filter((f) => referenced.has(f.path)));
const dropBytes = sum(unreferenced);

console.log(`public/ holds ${all.length} files, ${mb(sum(all))}`);
console.log(`  referenced   ${referenced.size} files, ${mb(keptBytes)}  → committed`);
console.log(`  unreferenced ${unreferenced.length} files, ${mb(dropBytes)}  → excluded`);

/* Group the excluded set by directory for a readable manifest. */
const byDir = new Map();
for (const f of unreferenced) {
  const dir = f.path.split("/").slice(0, -1).join("/");
  if (!byDir.has(dir)) byDir.set(dir, []);
  byDir.get(dir).push(f);
}

const lines = [
  "# What is not in this repository, and why",
  "",
  "Generated by `node scripts/media-manifest.mjs`. Re-run it after adding or",
  "removing images; it resolves references from `src/`, `sanity/` and",
  "`scripts/`, including the generated maps that components index into rather",
  "than writing paths out.",
  "",
  "## Photography",
  "",
  `The photo library was mirrored wholesale from the property's own sites, so`,
  `\`public/\` holds ${all.length} files (${mb(sum(all))}) while the site renders`,
  `${referenced.size} of them (${mb(keptBytes)}). The referenced set is committed —`,
  "including the mirrored suite photographs, which the site genuinely uses. The",
  `remaining ${unreferenced.length} files (${mb(dropBytes)}) are excluded: they are`,
  "duplicates at other crops, frames that lost their edit, and sources that were",
  "downscaled into the versions actually shipped. Nothing referenced by content",
  "is excluded, which is what makes the exclusion safe rather than lossy.",
  "",
];

if (byDir.size) {
  lines.push("### Excluded, by folder", "");
  lines.push("| folder | files | size |", "| --- | ---: | ---: |");
  for (const [dir, fs] of [...byDir].sort((a, b) => sum(b[1]) - sum(a[1]))) {
    lines.push(`| \`${dir}/\` | ${fs.length} | ${mb(sum(fs))} |`);
  }
  lines.push("");
}

lines.push(
  "## Everything else that is excluded",
  "",
  "| what | why |",
  "| --- | --- |",
  "| `node_modules/`, `.next/`, `out/`, `build/` | build products and dependencies; `package-lock.json` pins them |",
  "| `.env`, `.env.*` (except `.env.example`) | **credentials.** This repository is public. `.env.example` is committed and is all empty keys |",
  "| `*.tsbuildinfo`, `next-env.d.ts` | regenerated by the toolchain on every build |",
  "| `candidates/`, `car-pool/`, contact sheets | output of `scripts/car-pool.mjs` and `scripts/car-finalists.mjs` — harvested previews from Pexels/Unsplash/Pixabay. Third-party frames that were looked at and rejected have no business in the repository; only the one chosen placeholder is committed, in `public/media/` |",
  "| `lighthouse/`, `*.lhr.json`, `lh-*.json` | Lighthouse runs. Machine- and moment-specific; the conclusions are written up in the README instead |",
  "| `reports/`, `*-report.json`, `a11y-*.json`, `reveal-*.json`, `meta-*.json`, `i18n-*.json` | output of the QA scripts. Re-runnable in seconds; a stale committed report is worse than none |",
  "| `/shots/`, `/screens/`, `*.lighthouseci/` | screenshots and CI scratch |",
  "",
  "**The scripts themselves are committed.** `scripts/*.mjs` is how every claim",
  "in the README was measured, and a claim whose measurement cannot be re-run is",
  "an assertion. It is the outputs that are excluded, not the instruments.",
  "",
  "## Two files that look like output and are committed anyway",
  "",
  "| file | why it stays |",
  "| --- | --- |",
  "| `scripts/.suite-media.json` | Provenance, not a report. It records the original URL on creteholidayhome.com for every mirrored suite photograph, with its dimensions — in a repository that mirrors someone else's photography, knowing where each frame came from is the point. It is also the input `scripts/build-suite-images.mjs` reads, so dropping it would mean re-downloading the library to regenerate one TypeScript file. Contains public URLs and nothing else. |",
  "| `src/content/generated/*.ts` | Generated, but committed so the site builds from a clean clone without network access. Regenerate with `scripts/build-suite-images.mjs`. |",
  "",
);

writeFileSync("MEDIA-MANIFEST.md", lines.join("\n"));
console.log("\nwrote MEDIA-MANIFEST.md");

writeFileSync(
  ".gitignore.media",
  unreferenced.map((f) => "/" + f.path).join("\n") + "\n",
);
console.log(`wrote .gitignore.media (${unreferenced.length} paths)`);
