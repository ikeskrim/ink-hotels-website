/**
 * Turn the mirrored photography into a named, ordered image map.
 *
 *   node scripts/build-suite-images.mjs
 *
 * Order is editorial, not alphabetical: the first frame in each list is the
 * one that becomes the card and the detail-page hero, so it is chosen for what
 * it shows — the hot tub for Evexia, the courtyard for Eros, the tub laid for
 * two for Zoi — rather than by filename.
 *
 * Reads scripts/.suite-media.json, writes src/content/generated/suite-images.ts.
 */
import fs from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const manifest = JSON.parse(
  fs.readFileSync(path.join(ROOT, "scripts", ".suite-media.json"), "utf8"),
);

/** original filename (no extension) → position. Anything unlisted is dropped. */
const ORDER = {
  EVEXIA_IMAGES: {
    group: "evexia",
    files: [
      /* EVEXIA_3-16 leads: the tub with the sea running the full width behind
         it. The list used to open with EVEXIA_3-8 — the same tub against
         painted tiles and sky, a fine photograph with no sea in it — while the
         suite's own copy promises exactly the view that frame does not show.
         The card was contradicting the sentence under it. */
      "EVEXIA_3-16", "EVEXIA_3-8", "EVEXIA_3-9", "EVEXIA_3-7", "EVEXIA_3-15",
      "EVEXIA_3-5", "EVEXIA_3-3", "EVEXIA_3-2", "EVEXIA_3-1", "EVEXIA_3-21",
      "EVEXIA_3-14", "EVEXIA_3-4", "EVEXIA_3-10", "EVEXIA_3-19", "EVEXIA",
      "EVEXIA_3-13", "EVEXIA_3-12", "EVEXIA_3-20", "EVEXIA_3-18",
    ],
  },
  EROS_IMAGES: {
    group: "eros",
    files: [
      /* eros-1-new leads: the patio tub close, with the wooden screen and the
         grass — which is the suite's whole argument. EROS_2-3 is the same
         patio seen from across the courtyard, where the tub is small in frame
         and reads as furniture. */
      "eros-1-new", "EROS_2-3", "eros-5-new", "eros-6-new", "eros-8-new",
      "eros-2-new", "eros-10-new", "EROS_2-4", "eros-3-new", "EROS_2-5",
      "EROS_2-6", "EROS_2-7", "EROS_2-8", "EROS_2-9", "EROS_2-10", "EROS_2-1",
    ],
  },
  ZOI_IMAGES: {
    group: "zoi",
    files: [
      "ZOI-1-new", "ZOI-6-new", "ZOI-7-new", "ZOI-5-new", "ZOI-1", "ZOI-3",
      "ZOI-4-new", "ZOI-2", "ZOI-2-new", "ZOI-3-new", "ZOI-4", "ZOI_2-1",
      "ZOI_2-2", "ZOI_2-3", "ZOI_2-4", "ZOI_2-5",
    ],
  },
  /* The two shared courtyards from above — used on the collection page, not on
     either suite, because the frame contains both of them. */
  COURTYARD_IMAGES: { group: "eros", files: ["EROS-ZOI"] },
  /* Rethymno from the air, shot from the Evexia terrace. A town photograph,
     so it belongs to the place, not to the suite. */
  TOWN_IMAGES: { group: "evexia", files: ["Ink-5"] },

  HOUSE_IMAGES: {
    group: "houseOfEurope",
    files: Array.from({ length: 18 }, (_, i) => `Ink-Hotels-house-of-europe${i + 1}`),
  },
  PHOS_HOUSE_IMAGES: {
    group: "phos",
    files: Array.from({ length: 10 }, (_, i) => `Ink-hotels-Phos${i + 1}`),
  },
  BREAKFAST_IMAGES: {
    group: "breakfast",
    files: Array.from({ length: 6 }, (_, i) => `breakfast-${i + 1}`),
  },
  AGAPI_IMAGES: {
    group: "agapi",
    files: Array.from({ length: 16 }, (_, i) => `Agapi-${i + 1}`),
  },
  ELPIDA_IMAGES: {
    group: "elpida",
    files: Array.from({ length: 16 }, (_, i) => `Elpida-${i + 1}`),
  },
};

const base = (url) => url.split("/").pop().replace(/\.(jpg|jpeg|webp|png)$/i, "");

let out = `// AUTO-GENERATED by scripts/build-suite-images.mjs. Do not edit by hand.
//
// The Evexia, Eros and Zoi photography, plus the extra house, breakfast and
// suite material, mirrored from creteholidayhome.com. Ordering is editorial —
// index 0 is the frame that becomes the card and the detail-page hero.

`;

const missing = [];

for (const [name, { group, files }] of Object.entries(ORDER)) {
  const items = manifest[group] ?? [];
  const byName = new Map(items.map((it) => [base(it.url), it]));
  const picked = [];
  for (const f of files) {
    const hit = byName.get(f);
    if (hit) picked.push(hit);
    else missing.push(`${name}: ${f}`);
  }
  out += `export const ${name}: readonly string[] = [\n`;
  for (const p of picked) {
    out += `  "${p.file}", // ${base(p.url)} · ${p.w}×${p.h}\n`;
  }
  out += `];\n\n`;
  console.log(`${name.padEnd(22)} ${picked.length}`);
}

fs.writeFileSync(path.join(ROOT, "src", "content", "generated", "suite-images.ts"), out);
if (missing.length) console.log(`\nnot mirrored (skipped): ${missing.join(", ")}`);
console.log("\nwrote src/content/generated/suite-images.ts");
